def _font() -> str:
    """Segoe UI where it's installed (Windows), else matplotlib's own DejaVu Sans."""
    installed = {font.name for font in font_manager.fontManager.ttflist}
    return "Segoe UI" if "Segoe UI" in installed else "DejaVu Sans"


def _style(ax: Any, theme: Theme) -> None:
    """Recessive chrome: hairline grid and axes, muted ticks, no box."""
    ax.set_facecolor(theme.surface)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(theme.axis)
        ax.spines[side].set_linewidth(0.8)
    ax.tick_params(colors=theme.muted, labelsize=8, length=0, pad=4)
    ax.grid(color=theme.grid, linewidth=0.6)
    ax.set_axisbelow(True)


def calibration_figure(model: pd.DataFrame, baseline: pd.DataFrame, theme: Theme) -> Figure:
    """One panel per outcome: the chance given (x) against how often it happened (y).

    ``model`` and ``baseline`` are ``calibration_bins`` tables. Points on the diagonal are
    perfectly calibrated; above it, the outcome happened more often than predicted. The
    vertical bars are 95% Wilson intervals: long bars mean few cars in that bin.
    """
    with rc_context({"font.family": _font()}):
        fig = Figure(figsize=(8, 8.2), dpi=150, facecolor=theme.surface, layout="constrained")
        axes = fig.subplots(2, 2)
        for ax, outcome in zip(axes.flat, OUTCOME_TITLES, strict=True):
            _style(ax, theme)
            limit = 0.5 if outcome == "dnf" else 1.0
            ax.plot([0, limit], [0, limit], color=theme.axis, linewidth=1, zorder=1)
            series = (
                (baseline, theme.baseline, "Grid baseline"),
                (model, theme.model, "Full model"),
            )
            for table, color, label in series:
                rows = table[table["outcome"] == outcome]
                if rows.empty:
                    continue
                given, happened = rows["predicted"].to_numpy(), rows["observed"].to_numpy()
                ax.errorbar(
                    given,
                    happened,
                    yerr=[happened - rows["low"].to_numpy(), rows["high"].to_numpy() - happened],
                    fmt="-o",
                    color=color,
                    ecolor=to_rgba(color, 0.45),
                    elinewidth=1,
                    linewidth=2,
                    markersize=6,
                    markeredgecolor=theme.surface,
                    markeredgewidth=1.5,
                    label=label,
                    zorder=3,
                )
            ax.set_xlim(0, limit)
            ax.set_ylim(0, limit)
            ax.set_aspect("equal")
            ax.xaxis.set_major_formatter(PercentFormatter(1.0, decimals=0))
            ax.yaxis.set_major_formatter(PercentFormatter(1.0, decimals=0))
            ax.set_title(OUTCOME_TITLES[outcome], loc="left", color=theme.ink, fontsize=10)
        handles, labels = axes[0, 0].get_legend_handles_labels()
        fig.legend(
            handles[::-1],
            labels[::-1],
            loc="outside upper center",
            ncol=2,
            frameon=False,
            fontsize=9,
            labelcolor=theme.secondary,
        )
        fig.supxlabel("Chance given", color=theme.secondary, fontsize=9)
        fig.supylabel("How often it happened", color=theme.secondary, fontsize=9)
    return fig


def _bars(
    ax: Any, labels: list[str], values: list[float], fmt: str, theme: Theme, slots: int = 0
) -> None:
    """Thin horizontal bars from a zero line, listed top to bottom, each value at its tip.

    ``slots`` reserves room for that many bars (empty ones at the bottom), so two panels
    side by side get bars of the same thickness.
    """
    y = np.arange(len(values))[::-1]
    ax.set_ylim(len(values) - max(slots, len(values)) - 0.5, len(values) - 0.5)
    ax.barh(y, values, height=0.55, color=theme.model, zorder=2)
    reach = max(abs(v) for v in values) or 1.0
    for yi, value in zip(y, values, strict=True):
        side = 1 if value >= 0 else -1
        ax.text(
            value + side * reach * 0.03,
            yi,
            number(fmt, value),
            va="center",
            ha="left" if side > 0 else "right",
            color=theme.secondary,
            fontsize=8,
        )
    ax.set_yticks(y, labels, color=theme.ink, fontsize=8.5)
    ax.set_xticks([])
    ax.grid(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_visible(False)
    ax.vlines(0, -0.5, len(values) - 0.5, color=theme.axis, linewidth=1, zorder=3)
    low = min(0.0, min(values)) - (reach * 0.35 if min(values) < 0 else 0)
    ax.set_xlim(low, max(0.0, max(values)) + reach * 0.3)


def gain_bars(importance: list[dict[str, Any]]) -> tuple[list[str], list[float]]:
    """Inputs with at least 1% of the total gain, then one bar for all the others together."""
    shares = pd.DataFrame(importance)
    shown, rest = (
        shares[shares["gain_share"] >= MIN_SHARE],
        shares[shares["gain_share"] < MIN_SHARE],
    )
    labels = [FEATURE_LABELS.get(feature, feature) for feature in shown["feature"]]
    values = shown["gain_share"].tolist()
    if len(rest):
        labels.append(f"{len(rest)} other inputs")
        values.append(float(rest["gain_share"].sum()))
    return labels, values


def importance_figure(ranker: dict[str, Any], dnf: dict[str, Any], theme: Theme) -> Figure:
    """Left: the ranker's share of gain per input. Right: what the DNF model leans on."""
    ranker_bars = gain_bars(ranker["importance"])
    dnf_bars: tuple[list[str], list[float]] = ([], [])
    if dnf["kind"] == "logistic":
        rows = _dnf_inputs(dnf)
        dnf_bars = ([FEATURE_LABELS.get(f, f) for f, _ in rows], [value for _, value in rows])
    elif dnf["kind"] == "lightgbm":
        dnf_bars = gain_bars(dnf["importance"])
    slots = max(len(ranker_bars[1]), len(dnf_bars[1]))
    with rc_context({"font.family": _font()}):
        fig = Figure(figsize=(10, 4), dpi=150, facecolor=theme.surface, layout="constrained")
        left, right = fig.subplots(1, 2)
        for ax in (left, right):
            _style(ax, theme)
        _bars(left, *ranker_bars, "{:.1%}", theme, slots)
        left.set_title("Ranker: share of total gain", loc="left", color=theme.ink, fontsize=10)
        if dnf["kind"] == "logistic":
            _bars(right, *dnf_bars, "{:+.2f}", theme, slots)
            right.set_xlabel("← lowers the DNF chance · raises it →", color=theme.muted, fontsize=8)
            title = "DNF model: logistic coefficient per standard deviation"
        elif dnf["kind"] == "lightgbm":
            _bars(right, *dnf_bars, "{:.1%}", theme, slots)
            title = "DNF model: LightGBM share of total gain"
        else:
            right.set_axis_off()
            right.text(
                0,
                0.5,
                "Every car gets the field's recent DNF rate; no inputs.",
                transform=right.transAxes,
                color=theme.secondary,
                fontsize=9,
            )
            title = "DNF model: base rate"
        right.set_title(title, loc="left", color=theme.ink, fontsize=10)
    return fig


def save_figure(figure_for_theme: Callable[[Theme], Figure], path: Path) -> list[Path]:
    """Save a plot's light version at ``path`` and its dark version next to it."""
    written = []
    for name, theme in THEMES.items():
        target = path if name == "light" else path.with_name(f"{path.stem}-dark{path.suffix}")
        figure = figure_for_theme(theme)
        figure.savefig(target, facecolor=theme.surface)
        written.append(target)
    return written


def picture(stem: str, alt: str, width: int) -> str:
    """HTML that shows the dark version of a plot on GitHub's dark theme."""
    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="docs/{stem}-dark.png">\n'
        f'  <img alt="{alt}" src="docs/{stem}.png" width="{width}">\n'
        "</picture>"
    )


