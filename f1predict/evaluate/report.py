def number(fmt: str, value: float, signed: bool = False) -> str:
    """A value in a metric's format, with a true minus sign (and a + when ``signed``).

    A value that rounds to zero gets no sign at all, rather than "-0.00" or "+0%".
    """
    if pd.isna(value):
        return DASH
    text = (fmt.replace("{:", "{:+") if signed else fmt).format(value)
    if not any(digit in text for digit in "123456789"):
        text = text.lstrip("+-")
    return text.replace("-", MINUS)


def interval(fmt: str, low: float, high: float, signed: bool = False) -> str:
    """A confidence interval like ``[0.71, 0.83]``."""
    return f"[{number(fmt, low, signed)}, {number(fmt, high, signed)}]"


def difference(spec: Metric, value: float, low: float, high: float) -> str:
    """A signed difference and its CI: bold if clearly better, italic if clearly worse.

    Differences of two-decimal metrics (MAE, Spearman) get a third decimal, so small gaps
    like the practice ablations' don't all show as 0.00.
    """
    fmt = spec.fmt.replace(".2f", ".3f")
    text = f"{number(fmt, value, True)} {interval(fmt, low, high, True)}"
    verdict = clear_difference(spec.better, low, high)
    return f"**{text}**" if verdict > 0 else f"*{text}*" if verdict < 0 else text


def stacked(top: str, bottom: str) -> str:
    """Two lines in one table cell, the second one small."""
    return f"{top}<br><sub>{bottom}</sub>"


def markdown_table(header: list[str], rows: list[list[str]], right_from: int = 1) -> str:
    """A GitHub Markdown table; columns from ``right_from`` on are right-aligned."""
    marks = [":---" if i < right_from else "---:" for i in range(len(header))]
    lines = [f"| {' | '.join(header)} |", f"| {' | '.join(marks)} |"]
    return "\n".join(lines + [f"| {' | '.join(row)} |" for row in rows])


def _row(table: pd.DataFrame, season: int, metric: str, model: str | None = None) -> pd.Series:
    """The one row of a summary-like table for this season, metric (and model)."""
    rows = table[(table["season"] == season) & (table["metric"] == metric)]
    if model is not None:
        rows = rows[rows["model"] == model]
    return rows.iloc[0]


