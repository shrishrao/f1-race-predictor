def intro(full: Run, test: list[int], validation: list[int]) -> str:
    """What the tables show and how to read them."""
    counts = " and ".join(f"{season} ({full.race_count(season)} races)" for season in test)
    validated = " and ".join(str(season) for season in validation) or "none"
    return (
        "Every race was predicted by models trained only on the races before it. "
        f"Validation season: {validated} (the ranker's settings, the simulation temperature "
        f"and the DNF model were chosen there). Test seasons: {counts}. Values are season "
        "averages over races; brackets are 95% bootstrap confidence intervals, and "
        "differences are paired (both models scored on the same races). **Bold**: clearly "
        "better (the interval excludes 0); *italic*: clearly worse."
    )


def vs_baseline_table(model: Run, baseline: Run, seasons: list[int]) -> str:
    """Every metric for the baseline and the model per season, and the paired difference."""
    differences = compare(model.races, baseline.races)
    header = ["Metric", "Better"]
    for season in seasons:
        header += [f"{season} baseline", f"{season} model", f"{season} difference"]
    rows = []
    for metric in MODEL_METRICS:
        spec = METRICS[metric]
        row = [spec.label, spec.better]
        for season in seasons:
            gap = _row(differences, season, metric)
            row += [
                number(spec.fmt, baseline.value(season, metric)),
                number(spec.fmt, model.value(season, metric)),
                difference(spec, gap["difference"], gap["low"], gap["high"]),
            ]
        rows.append(row)
    return markdown_table(header, rows, right_from=2)


def _ablation_cells(runs: dict[str, Run]) -> dict[str, pd.DataFrame]:
    """Each variant's paired differences from the full model."""
    return {
        name: compare(run.races, runs[FULL].races) for name, run in runs.items() if name != FULL
    }


def _ablation_cell(
    runs: dict[str, Run], gaps: dict[str, pd.DataFrame], name: str, season: int, metric: str
) -> str:
    """A variant's value, with its difference from the full model below (none for the full)."""
    spec = METRICS[metric]
    value = number(spec.fmt, runs[name].value(season, metric))
    if name == FULL:
        return value
    gap = _row(gaps[name], season, metric)
    return stacked(value, difference(spec, gap["difference"], gap["low"], gap["high"]))


def ablation_summary(runs: dict[str, Run], seasons: list[int], metrics: list[str]) -> str:
    """One row per variant: a few metrics per season, each with its gap to the full model."""
    gaps = _ablation_cells(runs)
    header = ["Model"] + [f"{METRICS[m].label}, {s}" for m in metrics for s in seasons]
    rows = [
        [VARIANTS[name]]
        + [_ablation_cell(runs, gaps, name, s, m) for m in metrics for s in seasons]
        for name in runs
    ]
    return markdown_table(header, rows)


def ablation_detail(runs: dict[str, Run], season: int) -> str:
    """One season, every metric: one column per variant, gaps to the full model below."""
    gaps = _ablation_cells(runs)
    header = ["Metric", "Better", *(VARIANTS[name] for name in runs)]
    rows = [
        [METRICS[m].label, METRICS[m].better]
        + [_ablation_cell(runs, gaps, name, season, m) for name in runs]
        for m in MODEL_METRICS
    ]
    return markdown_table(header, rows, right_from=2)


def dnf_table(
    summary: pd.DataFrame, chosen: str, seasons: list[int], metrics: dict[str, Metric]
) -> str:
    """The DNF models per season: value with its CI; ``*`` marks the model in use."""
    header = ["Metric", "Model", *(str(season) for season in seasons)]
    rows = []
    for metric, spec in metrics.items():
        for i, kind in enumerate(DNF_KINDS):
            cells = []
            for season in seasons:
                row = _row(summary, season, metric, kind)
                cells.append(
                    stacked(
                        number(spec.fmt, row["value"]), interval(spec.fmt, row["low"], row["high"])
                    )
                )
            label = SHORT_LABELS[kind] + ("*" if kind == chosen else "")
            rows.append([spec.label if i == 0 else "", label, *cells])
    return markdown_table(header, rows, right_from=2)


def dnf_gap_table(differences: pd.DataFrame, seasons: list[int]) -> str:
    """Each learned DNF model minus the base rate, with paired CIs."""
    header = ["Metric", "Model", *(str(season) for season in seasons)]
    rows = []
    for metric, spec in DNF_SPECS.items():
        for i, kind in enumerate(k for k in DNF_KINDS if k in set(differences["model"])):
            cells = [
                difference(spec, row["difference"], row["low"], row["high"])
                for row in (_row(differences, season, metric, kind) for season in seasons)
            ]
            rows.append([spec.label if i == 0 else "", SHORT_LABELS[kind], *cells])
    return markdown_table(header, rows, right_from=2)


def dnf_effect_table(with_dnf: Run, without: Run, seasons: list[int]) -> str:
    """How simulating retirements changed each chance metric (with minus without, paired)."""
    gaps = compare(with_dnf.races, without.races)
    header = ["Metric", "Better", *(str(season) for season in seasons)]
    rows = []
    for metric in CHANCE_METRICS:
        spec = METRICS[metric]
        cells = [
            difference(spec, row["difference"], row["low"], row["high"])
            for row in (_row(gaps, season, metric) for season in seasons)
        ]
        rows.append([spec.label, spec.better, *cells])
    return markdown_table(header, rows, right_from=2)


def wilson_interval(happened: np.ndarray, n: np.ndarray, z: float = 1.96) -> tuple[Any, Any]:
    """95% Wilson score interval for the share ``happened / n``.

    Unlike "share plus or minus two standard errors" it never leaves 0-100% and stays honest
    for small bins and shares near 0 or 1, which is most of the win chances.
    """
    happened, n = np.asarray(happened, dtype="float64"), np.asarray(n, dtype="float64")
    share = happened / n
    centre = (share + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * np.sqrt(share * (1 - share) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return centre - half, centre + half


def calibration_bins(predictions: pd.DataFrame, seasons: list[int]) -> pd.DataFrame:
    """Calibration bins pooled over ``seasons``, with a Wilson interval for each share."""
    pooled = predictions[predictions["season"].isin(seasons)].assign(season=0)
    table = calibration_table(pooled)
    low, high = wilson_interval(table["observed"] * table["n"], table["n"])
    return table.assign(low=low, high=high)


def calibration_view(model: pd.DataFrame, baseline: pd.DataFrame) -> str:
    """The calibration plot as a table: per outcome and chance bin, cars, given vs happened."""
    keys = ["outcome", "bin_low", "bin_high"]
    merged = model.merge(baseline, on=keys, how="outer", suffixes=("", "_base"))
    merged["order"] = merged["outcome"].map({o: i for i, o in enumerate(OUTCOME_TITLES)})
    pct = "{:.0%}"
    header = ["Outcome", "Chance bin", "Model: cars", "Model: given → happened"]
    header += ["Baseline: cars", "Baseline: given → happened"]
    rows = []
    for row in merged.sort_values(["order", "bin_low"]).itertuples():
        cells = [OUTCOME_TITLES[row.outcome], f"{row.bin_low:.0%}{DASH}{row.bin_high:.0%}"]
        for suffix in ("", "_base"):
            n = getattr(row, f"n{suffix}")
            if pd.isna(n):
                cells += [DASH, DASH]
                continue
            given, happened = getattr(row, f"predicted{suffix}"), getattr(row, f"observed{suffix}")
            low, high = getattr(row, f"low{suffix}"), getattr(row, f"high{suffix}")
            cells += [
                f"{int(n)}",
                f"{number(pct, given)} → {number(pct, happened)} {interval(pct, low, high)}",
            ]
        rows.append(cells)
    return markdown_table(header, rows, right_from=2)


def importance_views(ranker: dict[str, Any], dnf: dict[str, Any]) -> str:
    """The importance plot as tables: the ranker's gain shares and the DNF model's inputs."""
    ranker_rows = [
        [FEATURE_LABELS.get(row["feature"], row["feature"]), f"{row['gain_share']:.1%}"]
        for row in ranker["importance"]
    ]
    parts = [
        "Ranker: each input's share of the total gain (how much its splits improved the ranking).",
        "",
        markdown_table(["Input", "Share of gain"], ranker_rows),
    ]
    rows = _dnf_inputs(dnf)
    if rows is not None:
        unit = "coefficient per SD" if dnf["kind"] == "logistic" else "share of gain"
        fmt = "{:+.3f}" if dnf["kind"] == "logistic" else "{:.1%}"
        parts += [
            "",
            f"DNF model ({KIND_LABELS[dnf['kind']]}): {unit}.",
            "",
            markdown_table(
                ["Input", unit.capitalize()],
                [[FEATURE_LABELS.get(f, f), number(fmt, v)] for f, v in rows],
            ),
        ]
    return "\n".join(parts)


def _dnf_inputs(dnf: dict[str, Any]) -> list[tuple[str, float]] | None:
    """The DNF model's inputs and their weights, biggest first (None for the base rate)."""
    if dnf["kind"] == "logistic":
        pairs = zip(dnf["features"], dnf["params"]["coef"], strict=True)
        return sorted(pairs, key=lambda pair: abs(pair[1]), reverse=True)
    if dnf["kind"] == "lightgbm":
        return [(row["feature"], row["gain_share"]) for row in dnf["importance"]]
    return None


