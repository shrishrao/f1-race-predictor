def replace_marked_section(text: str, content: str) -> str:
    """``text`` with everything between the results markers replaced by ``content``."""
    start, end = text.find(START), text.find(END)
    if start == -1 or end < start:
        raise ValueError(f"The README needs a {START} line and an {END} line after it.")
    return f"{text[: start + len(START)]}\n{content.strip()}\n{text[end:]}"


def _load_optional(name: str) -> Run | None:
    """A saved backtest, or None if it hasn't been run."""
    try:
        return load_run(name)
    except FileNotFoundError:
        return None


def write_report(
    docs_dir: Path | None = None, readme_path: Path | None = None
) -> tuple[list[Path], list[str]]:
    """Rebuild ``results.md``, both plots (light and dark) and the README's results section.

    Text files are written with LF line endings on every OS, as ``.gitattributes`` asks.

    The baseline and full-model backtests, the DNF comparison and the trained models are
    required. Ablations and the no-DNF run are left out if missing; the commands that would
    make them are returned with the files written.
    """
    docs = docs_dir or config.DOCS_DIR
    readme = readme_path or config.README_PATH
    baseline, full = load_run(BASELINE), load_run(FULL)
    dnf_summary, dnf_gaps = load_dnf_comparison()
    ranker_description = load_description(FULL)
    dnf_description = load_description(DNF_COMPARISON)
    optional = {
        name: _load_optional(name) for name in (*VARIANTS, NO_DNF) if name not in (FULL, BASELINE)
    }
    missing = [RUN_COMMANDS[name] for name, run in optional.items() if run is None]
    available = {FULL: full, BASELINE: baseline, **optional}
    runs = {name: available[name] for name in VARIANTS if available.get(name) is not None}

    seasons = full.seasons
    test = [season for season in config.TEST_SEASONS if season in seasons] or seasons
    validation = [season for season in seasons if season not in test]
    chosen = dnf_description["kind"]
    model_bins = calibration_bins(full.predictions, test)
    baseline_bins = calibration_bins(baseline.predictions, test)
    test_label = " and ".join(str(season) for season in test)

    detail = [
        "# Results",
        "",
        intro(full, test, validation),
        "",
        "## Full model vs the grid baseline",
        "",
        vs_baseline_table(full, baseline, test),
    ]
    if validation:
        detail += ["", f"Validation season ({', '.join(map(str, validation))}):", ""]
        detail += [vs_baseline_table(full, baseline, validation)]
    detail += ["", "## Ablations", "", "Below each value: the difference from the full model."]
    for season in seasons:
        kind = "test" if season in test else "validation"
        detail += ["", f"### {season} ({kind})", "", ablation_detail(runs, season)]
    detail += [
        "",
        "## DNF models",
        "",
        "Scored over the cars that started. `*` marks the model the simulation uses.",
        "",
        dnf_table(dnf_summary, chosen, seasons, DNF_SPECS | {"auc_dnf": AUC_METRIC}),
        "",
        "Each learned model minus the base rate:",
        "",
        dnf_gap_table(dnf_gaps, seasons),
    ]
    if optional[NO_DNF] is not None:
        detail += [
            "",
            "## Simulating retirements: with DNFs minus without",
            "",
            dnf_effect_table(full, optional[NO_DNF], seasons),
        ]
    detail += [
        "",
        f"## Calibration ({test_label} pooled)",
        "",
        "The table behind `calibration.png`: the brackets are 95% Wilson intervals.",
        "",
        calibration_view(model_bins, baseline_bins),
        "",
        "## What the models lean on",
        "",
        importance_views(ranker_description, dnf_description),
    ]

    summary = [
        GENERATED_NOTE,
        "",
        intro(full, test, validation),
        "",
        f"### Full model vs the grid baseline ({test_label})",
        "",
        vs_baseline_table(full, baseline, test),
        "",
        "### Ablations: what each group of features is worth",
        "",
        "Below each value: the difference from the full model.",
        "",
        ablation_summary(runs, test, SUMMARY_METRICS),
        "",
        f"### Retirements: the three DNF models ({test_label})",
        "",
        dnf_table(
            dnf_summary, chosen, test, {"brier_dnf": DNF_SPECS["brier_dnf"], "auc_dnf": AUC_METRIC}
        ),
        "",
        f"### Calibration ({test_label} pooled)",
        "",
        "Cars are grouped by the chance they were given (0-10%, 10-20%, ...). On the "
        "diagonal, things happened exactly as often as predicted; above it, more often. "
        "Vertical bars are 95% intervals: a long bar means few cars in that group.",
        "",
        picture("calibration", "Chance given vs how often it happened, per outcome", 720),
        "",
        "### What the models lean on",
        "",
        "Left: how much each input's splits improved the ranker. Right: how each input "
        "moves the log-odds of a retirement, per standard deviation of that input.",
        "",
        picture("importance", "Ranker gain shares and DNF model coefficients", 860),
        "",
        "Every table, the 2024 validation season, and the numbers behind both plots: "
        "[docs/results.md](docs/results.md).",
    ]

    docs.mkdir(parents=True, exist_ok=True)
    results_path = docs / "results.md"
    results_path.write_text("\n".join(detail) + "\n", encoding="utf-8", newline="\n")
    written = [results_path]
    written += save_figure(
        lambda theme: calibration_figure(model_bins, baseline_bins, theme), docs / "calibration.png"
    )
    written += save_figure(
        lambda theme: importance_figure(ranker_description, dnf_description, theme),
        docs / "importance.png",
    )
    text = readme.read_text(encoding="utf-8")
    readme.write_text(
        replace_marked_section(text, "\n".join(summary)), encoding="utf-8", newline="\n"
    )
    return [*written, readme], missing
