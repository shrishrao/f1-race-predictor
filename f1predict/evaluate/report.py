@dataclass(frozen=True)
class Run:
    """One saved backtest: season summaries, metrics per race, and the predictions."""

    name: str
    summary: pd.DataFrame
    races: pd.DataFrame
    predictions: pd.DataFrame

    @property
    def seasons(self) -> list[int]:
        """The seasons this backtest scored."""
        return sorted(int(season) for season in self.summary["season"].unique())

    def value(self, season: int, metric: str) -> float:
        """A season's average of one metric (NaN if the model doesn't produce it)."""
        rows = self.summary[(self.summary["season"] == season) & (self.summary["metric"] == metric)]
        return float(rows["value"].iloc[0]) if len(rows) else np.nan

    def race_count(self, season: int) -> int:
        """How many races of ``season`` were scored."""
        return int(self.summary.loc[self.summary["season"] == season, "races"].iloc[0])


def _missing(name: str, path: Path) -> FileNotFoundError:
    """The error for a saved result that isn't there, naming the command that makes it."""
    command = RUN_COMMANDS.get(name, "python -m f1predict train")
    return FileNotFoundError(f"No saved {name!r} at {path}. Run `{command}` first.")


def load_run(name: str) -> Run:
    """Load one saved backtest (``summary.json``, ``races.csv``, ``predictions.parquet``)."""
    folder = backtest_dir(name)
    path = folder / "summary.json"
    if not path.exists():
        raise _missing(name, path)
    seasons = json.loads(path.read_text(encoding="utf-8"))["seasons"]
    rows = [
        {"season": int(season), "metric": metric, **values, "races": block["races"]}
        for season, block in seasons.items()
        for metric, values in block["metrics"].items()
    ]
    return Run(
        name,
        pd.DataFrame(rows),
        pd.read_csv(folder / "races.csv"),
        pd.read_parquet(folder / "predictions.parquet"),
    )


def load_dnf_comparison(name: str = DNF_COMPARISON) -> tuple[pd.DataFrame, pd.DataFrame]:
    """A saved DNF comparison: its season summary and its differences from the base rate."""
    folder = backtest_dir(name)
    if not (folder / "summary.csv").exists():
        raise _missing(name, folder / "summary.csv")
    return pd.read_csv(folder / "summary.csv"), pd.read_csv(folder / "vs_base_rate.csv")


def load_description(name: str) -> dict[str, Any]:
    """The JSON description saved next to a trained model (e.g. ``ranker_full``)."""
    path = model_paths(name)[1]
    if not path.exists():
        raise _missing(name, path)
    return json.loads(path.read_text(encoding="utf-8"))


